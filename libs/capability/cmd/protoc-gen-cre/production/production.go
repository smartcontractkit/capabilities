// Dir is where the production protos are written, relative to the protos they come from. Each is at its production
// path in it, see feature.ProductionPath, so it is the include path they import each other by.
const Dir = "production"

const header = " Code generated by protoc-gen-cre. DO NOT EDIT.\n"

// Tags in descriptor.proto, which source locations are paths of.
const (
	fileDependency = 3
	fileMessage    = 4
	fileEnum       = 5
	fileService    = 6
	filePackage    = 2
	fileSyntax     = 12
	messageField   = 2
	messageNested  = 3
	messageEnum    = 4
	messageOneof   = 8
	enumValue      = 2
	serviceMethod  = 2
)

// Generate writes the production protos of the files plugin generates: what they tag with the features their
// services list as released, and the messages and enums that needs, without the feature options. Every feature must
// be listed as released or in progress, see checkFeatures. Each file has a production file in the production package,
// the development package without the x before its version, see feature.ProductionPackage, and each service is in it
// with its released methods, so a capability has production protos from its first generation, even with nothing
// released: a file with only its package, and a service with no methods, are valid protos. Every file of the
// capability must be generated in one run, as a feature can tag elements in several files, and what is released in
// one file can need a message from another.
func Generate(plugin *protogen.Plugin) error {
	files, err := protodesc.NewFiles(&descriptorpb.FileDescriptorSet{File: plugin.Request.ProtoFile})
	if err != nil {
		return err
	}

	p := &pruner{
		files:     files,
		types:     dynamicpb.NewTypes(files),
		generated: map[string]bool{},
		kept:      map[protoreflect.FullName]bool{},
		released:  map[string]bool{},
	}

	inProgress := map[string]bool{}
	var generated []protoreflect.FileDescriptor
	for _, file := range plugin.Files {
		p.generated[file.Desc.Path()] = file.Generate
		if !file.Generate {
			continue
		}

		generated = append(generated, file.Desc)
		if err = addFeatures(file.Desc, p.released, inProgress); err != nil {
			return err
		}
	}

	if err = checkFeatures(generated, p.released, inProgress); err != nil {
		return err
	}

	for _, fd := range generated {
		p.keepReleased(fd)
	}

	var pruned []*descriptorpb.FileDescriptorProto
	for _, file := range plugin.Files {
		if !file.Generate {
			continue
		}

		out, err := p.prune(file.Proto)
		if err != nil {
			return err
		}

		pruned = append(pruned, out)
	}

	// The production protos import each other by their production paths, and everything else as it is.
	set := &descriptorpb.FileDescriptorSet{}
	for _, file := range plugin.Request.ProtoFile {
		if !p.generated[file.GetName()] {
			set.File = append(set.File, file)
		}
	}

	set.File = append(set.File, pruned...)
	prodFiles, err := protodesc.NewFiles(set)
	if err != nil {
		return fmt.Errorf("invalid production protos: %w", err)
	}

	printer := &protoprint.Printer{}
	for _, file := range pruned {
		fd, err := prodFiles.FindFileByPath(file.GetName())
		if err != nil {
			return err
		}

		if err = printer.PrintProtoFile(fd, plugin.NewGeneratedFile(path.Join(Dir, file.GetName()), "")); err != nil {
			return err
		}
	}

	return nil
}

// pruner finds what the production protos keep, then cuts each file down to it.
type pruner struct {
	files *protoregistry.Files
	// types resolves the extensions in options, which protoc gives as unknown fields when no Go type for them is
	// linked into the plugin.
	types     *dynamicpb.Types
	generated map[string]bool
	kept      map[protoreflect.FullName]bool
	released  map[string]bool

	// imports are the files the file being pruned still uses.
	imports map[string]bool
}

func addFeatures(fd protoreflect.FileDescriptor, released, inProgress map[string]bool) error {
	services := fd.Services()
	for i := range services.Len() {
		// Through the options' Go type, as a compiler can give the lists as dynamic lists, which aren't []string.
		b, err := proto.Marshal(services.Get(i).Options())
		if err != nil {
			return err
		}

		opts := &descriptorpb.ServiceOptions{}
		if err = proto.Unmarshal(b, opts); err != nil {
			return err
		}

		for _, name := range proto.GetExtension(opts, feature.E_Released).([]string) {
			released[name] = true
		}

		for _, name := range proto.GetExtension(opts, feature.E_InProgress).([]string) {
			inProgress[name] = true
		}
	}

	return nil
}

// checkFeatures checks every feature the files tag is listed as released or in progress, and every one listed is
// one or the other and tags something, so a misspelt name, where it's tagged or where it's listed, fails generation
// rather than leaving what it tags unreleased.
func checkFeatures(files []protoreflect.FileDescriptor, released, inProgress map[string]bool) error {
	tagged := map[string][]string{}
	for _, fd := range files {
		walkTags(fd, func(element string, name string) {
			tagged[name] = append(tagged[name], element)
		})
	}

	var errs []error
	for _, name := range slices.Sorted(maps.Keys(tagged)) {
		if !released[name] && !inProgress[name] {
			errs = append(errs, fmt.Errorf("%s tagged %q, which is neither released nor in progress", strings.Join(tagged[name], ", "), name))
		}
	}

	listed := maps.Clone(released)
	maps.Copy(listed, inProgress)
	for _, name := range slices.Sorted(maps.Keys(listed)) {
		if released[name] && inProgress[name] {
			errs = append(errs, fmt.Errorf("feature %q is both released and in progress", name))
		}

		if len(tagged[name]) == 0 {
			errs = append(errs, fmt.Errorf("feature %q is listed but tags nothing", name))
		}
	}

	return errors.Join(errs...)
}

func walkTags(fd protoreflect.FileDescriptor, tagged func(element, name string)) {
	services := fd.Services()
	for i := range services.Len() {
		methods := services.Get(i).Methods()
		for j := range methods.Len() {
			if m := methods.Get(j); tag(m.Options(), feature.E_Method) != "" {
				tagged(string(m.FullName()), tag(m.Options(), feature.E_Method))
			}
		}
	}

	walkMessageTags(fd.Messages(), tagged)
	walkEnumTags(fd.Enums(), tagged)
}

func walkMessageTags(messages protoreflect.MessageDescriptors, tagged func(element, name string)) {
	for i := range messages.Len() {
		m := messages.Get(i)
		fields := m.Fields()
		for j := range fields.Len() {
			if f := fields.Get(j); tag(f.Options(), feature.E_Field) != "" {
				tagged(string(f.FullName()), tag(f.Options(), feature.E_Field))
			}
		}

		walkMessageTags(m.Messages(), tagged)
		walkEnumTags(m.Enums(), tagged)
	}
}

func walkEnumTags(enums protoreflect.EnumDescriptors, tagged func(element, name string)) {
	for i := range enums.Len() {
		e := enums.Get(i)
		values := e.Values()
		for j := range values.Len() {
			if v := values.Get(j); tag(v.Options(), feature.E_Value) != "" {
				tagged(string(e.FullName())+"."+string(v.Name()), tag(v.Options(), feature.E_Value))
			}
		}
	}
}

func tag(opts proto.Message, ext protoreflect.ExtensionType) string {
	t, _ := proto.GetExtension(opts, ext).(string)
	return t
}

func (p *pruner) isReleased(opts proto.Message, ext protoreflect.ExtensionType) bool {
	return p.released[tag(opts, ext)]
}

// keepReleased keeps fd's services, their released methods, the messages with released fields, and what they reach
// through released fields.
func (p *pruner) keepReleased(fd protoreflect.FileDescriptor) {
	services := fd.Services()
	for i := range services.Len() {
		p.kept[services.Get(i).FullName()] = true
		methods := services.Get(i).Methods()
		for j := range methods.Len() {
			if m := methods.Get(j); p.isReleased(m.Options(), feature.E_Method) {
				p.kept[m.FullName()] = true
				p.keepMessage(m.Input())
				p.keepMessage(m.Output())
			}
		}
	}

	p.keepReleasedMessages(fd.Messages())
}

// keepReleasedMessages keeps the messages with released fields, wherever they are nested, even if no released method
// uses them, so a retired method's messages stay released.
func (p *pruner) keepReleasedMessages(messages protoreflect.MessageDescriptors) {
	for i := range messages.Len() {
		m := messages.Get(i)
		fields := m.Fields()
		for j := range fields.Len() {
			if p.isReleased(fields.Get(j).Options(), feature.E_Field) {
				p.keepMessage(m)
			}
		}

		p.keepReleasedMessages(m.Messages())
	}
}

// keepMessage keeps m and its released fields. A map's entry is not tagged, so its key and value are kept with it.
func (p *pruner) keepMessage(m protoreflect.MessageDescriptor) {
	if !p.keep(m) {
		return
	}

	fields := m.Fields()
	for i := range fields.Len() {
		if f := fields.Get(i); m.IsMapEntry() || p.isReleased(f.Options(), feature.E_Field) {
			p.kept[f.FullName()] = true
			if fm := f.Message(); fm != nil {
				p.keepMessage(fm)
			}

			if e := f.Enum(); e != nil {
				p.keepEnum(e)
			}
		}
	}
}

func (p *pruner) keepEnum(e protoreflect.EnumDescriptor) {
	if !p.keep(e) {
		return
	}

	values := e.Values()
	for i := range values.Len() {
		if v := values.Get(i); p.isReleased(v.Options(), feature.E_Value) {
			p.kept[v.FullName()] = true
		}
	}
}

// keep keeps a message or enum, and the messages it is nested in, but none of their fields, reporting whether it
// was newly kept. What is from the files that are not being generated is imported as it is, so it is not kept.
func (p *pruner) keep(d protoreflect.Descriptor) bool {
	if p.kept[d.FullName()] || !p.generated[d.ParentFile().Path()] {
		return false
	}

	p.kept[d.FullName()] = true
	if parent, ok := d.Parent().(protoreflect.MessageDescriptor); ok {
		p.keep(parent)
	}

	return true
}

// prune returns in with only what is kept, in the production package and at its production path.
func (p *pruner) prune(in *descriptorpb.FileDescriptorProto) (*descriptorpb.FileDescriptorProto, error) {
	if len(in.Extension) > 0 {
		return nil, fmt.Errorf("%s: extensions are not supported in capability protos", in.GetName())
	}

	pkg, err := feature.ProductionPackage(protoreflect.FullName(in.GetPackage()))
	if err != nil {
		return nil, fmt.Errorf("%s: %w", in.GetName(), err)
	}

	p.imports = map[string]bool{}
	moved := moves{}
	out := proto.CloneOf(in)
	out.Package = proto.String(string(pkg))
	name, err := p.productionPath(in.GetName())
	if err != nil {
		return nil, err
	}

	out.Name = proto.String(name)
	if out.MessageType, err = filter(in.MessageType, []int32{fileMessage}, moved, func(m *descriptorpb.DescriptorProto, at []int32) (*descriptorpb.DescriptorProto, error) {
		return p.pruneMessage(in.GetPackage(), m, at, moved)
	}); err != nil {
		return nil, err
	}

	if out.EnumType, err = filter(in.EnumType, []int32{fileEnum}, moved, func(e *descriptorpb.EnumDescriptorProto, at []int32) (*descriptorpb.EnumDescriptorProto, error) {
		return p.pruneEnum(in.GetPackage(), e, at, moved)
	}); err != nil {
		return nil, err
	}

	if out.Service, err = filter(in.Service, []int32{fileService}, moved, func(s *descriptorpb.ServiceDescriptorProto, at []int32) (*descriptorpb.ServiceDescriptorProto, error) {
		return p.pruneService(in.GetPackage(), s, at, moved)
	}); err != nil {
		return nil, err
	}

	if out.Options, err = options(p, in.Options); err != nil {
		return nil, err
	}

	// The SDKs generate the production protos into packages of their own.
	if out.Options != nil {
		out.Options.GoPackage = nil
		if proto.Size(out.Options) == 0 {
			out.Options = nil
		}
	}

	out.Dependency, _ = filter(in.Dependency, []int32{fileDependency}, moved, func(dep string, _ []int32) (string, error) {
		if !p.imports[dep] {
			return "", nil
		}

		if p.generated[dep] {
			return p.productionPath(dep)
		}

		return dep, nil
	})

	out.PublicDependency = nil
	out.WeakDependency = nil

	out.SourceCodeInfo = &descriptorpb.SourceCodeInfo{}
	for _, loc := range in.GetSourceCodeInfo().GetLocation() {
		// The package is not the one its comments are about.
		if slices.Equal(loc.Path, []int32{filePackage}) {
			continue
		}

		if at, ok := moved.move(loc.Path); ok {
			loc = proto.CloneOf(loc)
			loc.Path = at
			out.SourceCodeInfo.Location = append(out.SourceCodeInfo.Location, loc)
		}
	}

	markGenerated(out)
	return out, nil
}

func markGenerated(file *descriptorpb.FileDescriptorProto) {
	locs := file.SourceCodeInfo.Location
	i := slices.IndexFunc(locs, func(loc *descriptorpb.SourceCodeInfo_Location) bool {
		return slices.Equal(loc.Path, []int32{fileSyntax})
	})

	if i < 0 {
		// Without a span, the printer can't place the syntax, so the header goes at the start of the file.
		file.SourceCodeInfo.Location = append(locs, &descriptorpb.SourceCodeInfo_Location{
			Path: []int32{fileSyntax}, Span: []int32{0, 0, 0}, LeadingDetachedComments: []string{header},
		})

		return
	}

	locs[i].LeadingDetachedComments = append([]string{header}, locs[i].LeadingDetachedComments...)
}

func (p *pruner) pruneMessage(scope string, in *descriptorpb.DescriptorProto, at []int32, moved moves) (*descriptorpb.DescriptorProto, error) {
	name := scope + "." + in.GetName()
	if !p.kept[protoreflect.FullName(name)] {
		return nil, nil
	}

	if len(in.Extension) > 0 {
		return nil, fmt.Errorf("%s: extensions are not supported in capability protos", name)
	}

	out := proto.CloneOf(in)
	var err error
	if out.Field, err = filter(in.Field, append(slices.Clone(at), messageField), moved, func(f *descriptorpb.FieldDescriptorProto, _ []int32) (*descriptorpb.FieldDescriptorProto, error) {
		if !p.kept[protoreflect.FullName(name+"."+f.GetName())] {
			return nil, nil
		}

		f = proto.CloneOf(f)
		if err = p.use(f.TypeName); err != nil {
			return nil, err
		}

		f.Options, err = options(p, f.Options)
		return f, err
	}); err != nil {
		return nil, err
	}

	if out.NestedType, err = filter(in.NestedType, append(slices.Clone(at), messageNested), moved, func(m *descriptorpb.DescriptorProto, at []int32) (*descriptorpb.DescriptorProto, error) {
		return p.pruneMessage(name, m, at, moved)
	}); err != nil {
		return nil, err
	}

	if out.EnumType, err = filter(in.EnumType, append(slices.Clone(at), messageEnum), moved, func(e *descriptorpb.EnumDescriptorProto, at []int32) (*descriptorpb.EnumDescriptorProto, error) {
		return p.pruneEnum(name, e, at, moved)
	}); err != nil {
		return nil, err
	}

	oneofs := append(slices.Clone(at), messageOneof)
	out.OneofDecl, _ = filter(in.OneofDecl, oneofs, moved, func(o *descriptorpb.OneofDescriptorProto, at []int32) (*descriptorpb.OneofDescriptorProto, error) {
		i := at[len(at)-1]
		if slices.ContainsFunc(out.Field, func(f *descriptorpb.FieldDescriptorProto) bool { return f.OneofIndex != nil && *f.OneofIndex == i }) {
			return o, nil
		}

		return nil, nil
	})

	for _, f := range out.Field {
		if f.OneofIndex != nil {
			f.OneofIndex = proto.Int32(moved[key(append(oneofs, *f.OneofIndex))])
		}
	}

	out.Options, err = options(p, in.Options)
	return out, err
}

// An enum's values are in its parent's scope, as they are in protobuf, so they are named by scope, not by the enum.
func (p *pruner) pruneEnum(scope string, in *descriptorpb.EnumDescriptorProto, at []int32, moved moves) (*descriptorpb.EnumDescriptorProto, error) {
	name := scope + "." + in.GetName()
	if !p.kept[protoreflect.FullName(name)] {
		return nil, nil
	}

	if len(in.Value) > 0 && !p.kept[protoreflect.FullName(scope+"."+in.Value[0].GetName())] {
		return nil, fmt.Errorf("%s is released, so its first value, %s, must be released too", name, in.Value[0].GetName())
	}

	out := proto.CloneOf(in)
	var err error
	if out.Value, err = filter(in.Value, append(slices.Clone(at), enumValue), moved, func(v *descriptorpb.EnumValueDescriptorProto, _ []int32) (*descriptorpb.EnumValueDescriptorProto, error) {
		if !p.kept[protoreflect.FullName(scope+"."+v.GetName())] {
			return nil, nil
		}

		v = proto.CloneOf(v)
		v.Options, err = options(p, v.Options)
		return v, err
	}); err != nil {
		return nil, err
	}

	out.Options, err = options(p, in.Options)
	return out, err
}

func (p *pruner) pruneService(scope string, in *descriptorpb.ServiceDescriptorProto, at []int32, moved moves) (*descriptorpb.ServiceDescriptorProto, error) {
	name := scope + "." + in.GetName()
	if !p.kept[protoreflect.FullName(name)] {
		return nil, nil
	}

	out := proto.CloneOf(in)
	var err error
	if out.Method, err = filter(in.Method, append(slices.Clone(at), serviceMethod), moved, func(m *descriptorpb.MethodDescriptorProto, _ []int32) (*descriptorpb.MethodDescriptorProto, error) {
		if !p.kept[protoreflect.FullName(name+"."+m.GetName())] {
			return nil, nil
		}

		m = proto.CloneOf(m)
		if err = p.use(m.InputType); err != nil {
			return nil, err
		}

		if err = p.use(m.OutputType); err != nil {
			return nil, err
		}

		m.Options, err = options(p, m.Options)
		return m, err
	}); err != nil {
		return nil, err
	}

	out.Options, err = options(p, in.Options)
	return out, err
}

func (p *pruner) productionPath(file string) (string, error) {
	fd, err := p.files.FindFileByPath(file)
	if err != nil {
		return "", err
	}

	return feature.ProductionPath(fd.Package(), file)
}

// use notes the file the type a field or method names is from as imported, and renames it to its production
// name if it is from the files being generated.
func (p *pruner) use(typeName *string) error {
	if typeName == nil {
		return nil
	}

	d, err := p.files.FindDescriptorByName(protoreflect.FullName(strings.TrimPrefix(*typeName, ".")))
	if err != nil {
		return err
	}

	p.imports[d.ParentFile().Path()] = true
	if !p.generated[d.ParentFile().Path()] {
		return nil
	}

	name, err := feature.ProductionName(d)
	*typeName = "." + string(name)
	return err
}

// options returns opts without its feature options, noting the files of the extensions it still has as imported.
func options[M proto.Message](p *pruner, opts M) (M, error) {
	var none M
	if !opts.ProtoReflect().IsValid() {
		return none, nil
	}

	b, err := proto.Marshal(opts)
	if err != nil {
		return none, err
	}

	resolved := opts.ProtoReflect().New()
	if err = (proto.UnmarshalOptions{Resolver: p.types}).Unmarshal(b, resolved.Interface()); err != nil {
		return none, err
	}

	var tags []protoreflect.FieldDescriptor
	resolved.Range(func(fd protoreflect.FieldDescriptor, _ protoreflect.Value) bool {
		switch {
		case !fd.IsExtension():
		case fd.FullName() == feature.E_Field.TypeDescriptor().FullName(),
			fd.FullName() == feature.E_Method.TypeDescriptor().FullName(),
			fd.FullName() == feature.E_Value.TypeDescriptor().FullName(),
			fd.FullName() == feature.E_Released.TypeDescriptor().FullName(),
			fd.FullName() == feature.E_InProgress.TypeDescriptor().FullName():
			tags = append(tags, fd)
		default:
			p.imports[fd.ParentFile().Path()] = true
		}

		return true
	})

	for _, fd := range tags {
		resolved.Clear(fd)
	}

	if proto.Size(resolved.Interface()) == 0 {
		return none, nil
	}

	// Back to the options' own type, so it can be given to protodesc.
	if b, err = proto.Marshal(resolved.Interface()); err != nil {
		return none, err
	}

	out := opts.ProtoReflect().New().Interface().(M)
	return out, proto.Unmarshal(b, out)
}

// moves maps the path of each element kept to its index once pruned.
type moves map[string]int32

func key(path []int32) string {
	return fmt.Sprint(path)
}

// scope is the kind of element a path is in, which decides which of its tags are lists of elements that pruning
// can move.
type scope int

const (
	inLeaf scope = iota
	inFile
	inMessage
	inEnum
	inService
)

var elements = map[scope]map[int32]scope{
	inFile:    {fileDependency: inLeaf, fileMessage: inMessage, fileEnum: inEnum, fileService: inService},
	inMessage: {messageField: inLeaf, messageNested: inMessage, messageEnum: inEnum, messageOneof: inLeaf},
	inEnum:    {enumValue: inLeaf},
	inService: {serviceMethod: inLeaf},
}

// move returns where the source location at path is once pruned, or false if it was pruned.
func (m moves) move(path []int32) ([]int32, bool) {
	out := slices.Clone(path)
	in := inFile
	for i := 0; i+1 < len(path); i += 2 {
		next, ok := elements[in][path[i]]
		if !ok {
			break
		}

		at, ok := m[key(path[:i+2])]
		if !ok {
			return nil, false
		}

		out[i+1] = at
		in = next
	}

	return out, true
}

// filter returns the elements of in that prune keeps, prune returning the zero T for those it does not, and
// records where each kept element moved to. at is the path of in.
func filter[T comparable](in []T, at []int32, moved moves, prune func(T, []int32) (T, error)) ([]T, error) {
	var out []T
	var none T
	for i, e := range in {
		path := append(slices.Clone(at), int32(i))
		kept, err := prune(e, path)
		if err != nil {
			return nil, err
		}

		if kept != none {
			moved[key(path)] = int32(len(out)) //nolint:gosec // No more than in, which a descriptor indexes by int32.
			out = append(out, kept)
		}
	}

	return out, nil
}
