// Tests here are not parallel: cli.New sets cobra globals.
func command(t *testing.T, args ...string) (*cobra.Command, *strings.Builder) {
	t.Helper()

	cmd, err := newCommand()
	require.NoError(t, err)
	var out strings.Builder
	cmd.SetArgs(args)
	cmd.SetOut(&out)
	cmd.SetErr(&out)
	return cmd, &out
}

func TestPromptsForMissingArgs(t *testing.T) {
	// The name is rejected before anything is generated, so this only exercises reading them.
	cmd, out := command(t, "--action", "--out-dir", t.TempDir())
	cmd.SetIn(strings.NewReader("example\nBad\n"))

	require.ErrorContains(t, cmd.Execute(), `"Bad" must be lowercase`)
	assert.Contains(t, out.String(), "Category")
	assert.Contains(t, out.String(), "Capability")
}

func TestRejects(t *testing.T) {
	for name, args := range map[string][]string{
		"no kind":      {"--category", "example", "--name", "thing"},
		"bad category": {"--action", "--category", "Example", "--name", "thing"},
		"bad name":     {"--action", "--category", "example", "--name", "my-thing"},
	} {
		t.Run(name, func(t *testing.T) {
			cmd, _ := command(t, append(args, "--out-dir", t.TempDir())...)
			assert.Error(t, cmd.Execute())
		})
	}
}

func TestCleanKeepsAddedFiles(t *testing.T) {
	s := &scaffold{}
	s.Category, s.Name, s.Trigger, s.Action = "example", "thing", true, true
	dir := t.TempDir()

	files := map[string]string{
		"main.go":               "package main\n",
		"go.mod":                "module x\n",
		"protos/client.pb.go":   "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage protos\n",
		"service/capability.go": "package service\n",
		"service/extra.go":      "package service\n",
		"service/extra_test.go": "package service\n",
		"README.md":             "mine\n",
	}

	for name, content := range files {
		path := filepath.Join(dir, filepath.FromSlash(name))
		require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o700))
		require.NoError(t, os.WriteFile(path, []byte(content), 0o600))
	}

	require.NoError(t, s.clean(dir))
	for _, kept := range []string{"service/extra.go", "service/extra_test.go", "README.md"} {
		assert.FileExists(t, filepath.Join(dir, kept))
	}

	for _, gone := range []string{"main.go", "go.mod", "protos/client.pb.go", "service/capability.go"} {
		assert.NoFileExists(t, filepath.Join(dir, gone))
		assert.NoDirExists(t, filepath.Join(dir, gone))
	}
}

func TestNoModuleFiles(t *testing.T) {
	s := &scaffold{}
	s.Category, s.Name, s.Action, s.NoModule = "example", "thing", true, true
	files, err := s.files()
	require.NoError(t, err)
	assert.NotContains(t, files, "go.mod")
	assert.NotContains(t, files, "project.json")

	s.NoModule = false
	files, err = s.files()
	require.NoError(t, err)
	assert.Contains(t, files, "go.mod")
}
